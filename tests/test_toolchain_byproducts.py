"""A lockfile the project's toolchain writes while a stage runs it is not the stage's edit.

A live Rust bug fix (Claude models, 2026-11-13) paused 65 seconds in: the Planner ran Cargo to read
a project with no ``Cargo.lock``, Cargo wrote one, and the read-only stage had "changed the
repository". A Builder that ran ``cargo test`` was refused for a file outside its assigned paths.
Real Git workspaces; no provider is launched.
"""

from __future__ import annotations

import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import MagicMock

import autocode_role_launch as role_launch
import autocode_support as support
import autocode_toolchain_byproducts as byproducts

MANIFEST = '[package]\nname = "pager"\nversion = "0.1.0"\nedition = "2021"\n'
LOCK = '# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "pager"\n'
SEED = {"Cargo.toml": MANIFEST, "src/lib.rs": "pub fn one() -> u32 {\n    1\n}\n"}


def git(cwd, *args):
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


class Workspace(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="byproducts-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve() / "project"
        self.root.mkdir()
        self.write(SEED)
        git(self.root, "init", "-q")
        git(self.root, "config", "maintenance.auto", "false")  # see tests.test_verify.Project
        git(self.root, "config", "gc.auto", "0")
        self.commit("seed")

    def write(self, files):
        for name, text in files.items():
            (self.root / name).parent.mkdir(parents=True, exist_ok=True)
            (self.root / name).write_text(text)

    def commit(self, message):
        git(self.root, "add", "-A")
        git(self.root, "-c", "user.name=t", "-c", "user.email=t@example.test", "commit", "-qm", message)

    def snapshot(self):
        return support.snapshot(self.root)


class DiscardTests(Workspace):
    def test_a_lockfile_cargo_wrote_during_the_stage_is_removed(self):
        before = self.snapshot()
        self.write({"Cargo.lock": LOCK})
        self.assertEqual(["Cargo.lock"], byproducts.created(self.root, before["files"]))
        self.assertEqual(["Cargo.lock"], byproducts.discard(self.root, before))
        self.assertFalse((self.root / "Cargo.lock").exists())
        self.assertEqual(before["revision"], self.snapshot()["revision"])

    def test_a_workspace_member_lockfile_is_removed_beside_its_own_manifest(self):
        self.write({"crates/core/Cargo.toml": MANIFEST})
        self.commit("member")
        before = self.snapshot()
        self.write({"crates/core/Cargo.lock": LOCK})
        self.assertEqual(["crates/core/Cargo.lock"], byproducts.discard(self.root, before))

    def test_a_lockfile_the_project_already_had_is_never_touched(self):
        for committed in (False, True):
            with self.subTest(committed=committed):
                self.write({"Cargo.lock": LOCK})
                if committed:
                    self.commit("lock")
                before = self.snapshot()
                self.write({"Cargo.lock": LOCK + 'version = "0.1.0"\n'})  # the stage changed it: an edit
                self.assertEqual([], byproducts.discard(self.root, before))
                self.assertTrue((self.root / "Cargo.lock").is_file())
                self.assertNotEqual(before["revision"], self.snapshot()["revision"])

    def test_only_a_lockfile_beside_its_manifest_qualifies(self):
        before = self.snapshot()
        self.write({"docs/Cargo.lock": LOCK, "notes.lock": LOCK, "src/extra.rs": "pub fn two() {}\n"})
        self.assertEqual([], byproducts.discard(self.root, before))
        for name in ("docs/Cargo.lock", "notes.lock", "src/extra.rs"):
            self.assertTrue((self.root / name).is_file(), name)

    def test_a_link_named_like_a_lockfile_is_left(self):
        before = self.snapshot()
        (self.root / "Cargo.lock").symlink_to("Cargo.toml")
        self.assertEqual([], byproducts.discard(self.root, before))
        self.assertTrue((self.root / "Cargo.lock").is_symlink())

    def test_a_lockfile_inside_the_assigned_paths_is_the_builders_own(self):
        for owned in (["Cargo.lock"], ["Cargo.lock", "src/"], ["Cargo.lock/"]):
            with self.subTest(owned=owned):
                before = self.snapshot()
                self.write({"Cargo.lock": LOCK})
                self.assertEqual([], byproducts.discard(self.root, before, owned=owned))
                self.assertTrue((self.root / "Cargo.lock").is_file())
                (self.root / "Cargo.lock").unlink()

    def test_a_snapshot_that_cannot_show_what_existed_removes_nothing(self):
        self.write({"Cargo.lock": LOCK})
        for before in (None, {}, {"revision": "r1"}, {"files": None}):
            with self.subTest(before=before):
                self.assertEqual([], byproducts.discard(self.root, before))
        self.assertEqual([], byproducts.discard(None, self.snapshot()))
        self.assertTrue((self.root / "Cargo.lock").is_file())


class StageTests(Workspace):
    """role_launch.record_after: what the stage's after-snapshot and record show."""

    def after(self, state, *, allow_write):
        before = self.snapshot()
        self.write({"Cargo.lock": LOCK})
        record = {}
        base = Path(self.temp.name) / "stage-01"
        after = role_launch.record_after(
            state,
            record,
            self.root,
            base,
            before,
            Path(self.temp.name) / "missing.jsonl",
            save=MagicMock(),
            allow_write=allow_write,
        )
        return before, after, record

    def test_a_read_only_stage_that_ran_cargo_leaves_the_repository_unchanged(self):
        before, after, record = self.after({}, allow_write=False)
        self.assertEqual(before["revision"], after["revision"])  # no PAUSED_STALE_VALIDATION
        self.assertEqual([], record["changed_files"])
        self.assertEqual(["Cargo.lock"], record["toolchain_byproducts"])
        self.assertFalse((self.root / "Cargo.lock").exists())

    def test_a_read_only_stage_that_wrote_anything_else_still_shows_it(self):
        before = self.snapshot()
        self.write({"Cargo.lock": LOCK, "src/lib.rs": "pub fn one() -> u32 {\n    2\n}\n"})
        record = {}
        after = role_launch.record_after(
            {}, record, self.root, Path(self.temp.name) / "stage-01", before, Path("missing.jsonl"), save=MagicMock()
        )
        self.assertNotEqual(before["revision"], after["revision"])
        self.assertEqual(["src/lib.rs"], record["changed_files"])

    def test_a_builder_is_not_charged_with_the_lockfile_outside_its_paths(self):
        state = {"current_task": {"affected_paths": ["src/lib.rs"]}}
        _, _, record = self.after(state, allow_write=True)
        self.assertEqual([], record["changed_files"])
        self.assertEqual(["Cargo.lock"], record["toolchain_byproducts"])

    def test_a_builder_keeps_a_lockfile_its_task_owns_or_when_it_may_write_anywhere(self):
        for state in ({"current_task": {"affected_paths": ["Cargo.lock", "src/"]}}, {"current_task": {}}, {}):
            with self.subTest(state=state):
                _, _, record = self.after(state, allow_write=True)
                self.assertEqual(["Cargo.lock"], record["changed_files"])
                self.assertNotIn("toolchain_byproducts", record)
                (self.root / "Cargo.lock").unlink()


if __name__ == "__main__":
    unittest.main()
