"""Which ignored files a project's build wrote may enter an in-place run's clean test copies."""

import subprocess
import tempfile
import unittest
from pathlib import Path

import autocode_build_outputs as build_outputs

# vcs-versioning's file, as hatch-vcs wrote it for Humanize (src/humanize/_version.py), 2026-11-23.
HATCH_VCS = b"""# file generated by vcs-versioning
# don't change, don't track in version control
from __future__ import annotations

__all__ = [
    "__version__",
    "__version_tuple__",
    "version",
    "version_tuple",
    "__commit_id__",
    "commit_id",
]

version: str
__version__: str
__version_tuple__: tuple[int | str, ...]
version_tuple: tuple[int | str, ...]
commit_id: str | None
__commit_id__: str | None

__version__ = version = '4.16.1.dev20'
__version_tuple__ = version_tuple = (4, 16, 1, 'dev20')

__commit_id__ = commit_id = None
"""
# setuptools-scm 8's template.
SETUPTOOLS_SCM = b"""# file generated by setuptools-scm
# don't change, don't track in version control

__all__ = ["__version__", "__version_tuple__", "version", "version_tuple"]

TYPE_CHECKING = False
if TYPE_CHECKING:
    from typing import Tuple
    from typing import Union

    VERSION_TUPLE = Tuple[Union[int, str], ...]
else:
    VERSION_TUPLE = object

version: str
__version__: str
__version_tuple__: VERSION_TUPLE
version_tuple: VERSION_TUPLE

__version__ = version = '0.1.dev1+g1234567.d20261123'
__version_tuple__ = version_tuple = (0, 1, 'dev1', 'g1234567.d20261123')
"""
OLD_SETUPTOOLS_SCM = (
    b"# coding: utf-8\n# file generated by setuptools_scm\nversion = '1.2.3'\nversion_tuple = (1, 2, 3)\n"
)


class InertTests(unittest.TestCase):
    def test_version_files_the_builds_write_hold_only_data(self):
        for data in (
            HATCH_VCS,
            SETUPTOOLS_SCM,
            OLD_SETUPTOOLS_SCM,
            b"",
            b"VERSION = -1\nMETA = {'a': [1, 2]}\n",
            b"import typing\nx: typing.Optional[str] = None\nS = {+1}\n",
        ):
            with self.subTest(data=data[:40]):
                self.assertTrue(build_outputs.inert("pkg/_version.py", data))

    def test_a_module_that_could_run_or_patch_code_is_not_data(self):
        for text in (
            "import calc\ncalc.add = lambda a, b: a + b\n",
            "VERSION = '1'\nimport os\n",
            "from os import system\n",
            "from . import calc\n",
            "from typing import *\n",
            "VERSION = str(1)\n",
            "VERSION = undefined_name\n",
            "VERSION = '1'\ndef version():\n    return VERSION\n",
            "class Version:\n    pass\n",
            "__getattr__ = object\n",
            "__path__ = ['elsewhere']\n",
            "if open('x'):\n    VERSION = '1'\n",
            "VERSION = '1'\nprint(VERSION)\n",
            "x: int = len('a')\n",
            "x: print('a') = 1\n",
            "obj.attr = 1\n",
            "VERSION = f'{1}'\n",
        ):
            with self.subTest(text=text):
                self.assertFalse(build_outputs.inert("pkg/_version.py", text.encode()))

    def test_only_a_parsable_python_file_can_be_data(self):
        self.assertFalse(build_outputs.inert("pkg/version.js", b"VERSION = '1'\n"))
        self.assertFalse(build_outputs.inert("pkg/_version.py", b"VERSION = (\n"))
        self.assertFalse(build_outputs.inert("pkg/_version.py", b"\xff\xfe"))


class DeclarationTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="build-outputs-")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.git("init", "-q")

    def git(self, *args):
        return subprocess.run(["git", "-C", str(self.root), *args], check=True, capture_output=True, text=True).stdout

    def commit(self, files):
        for name, text in files.items():
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        self.git("add", "-A")
        self.git("-c", "user.name=T", "-c", "user.email=t@example.test", "commit", "-qm", "c")
        return self.git("rev-parse", "HEAD").strip()

    def test_the_packaging_of_the_files_project_declares_it_relative_to_itself(self):
        base = self.commit(
            {
                "pyproject.toml": '[tool.setuptools_scm]\nwrite_to = "src/pkg/_version.py"\n',
                "backend/setup.cfg": "[metadata]\nname = b\n",
                "backend/setup.py": "setup(use_scm_version={'write_to': './app/_version.py'})\n",
            }
        )
        self.assertEqual("pyproject.toml", build_outputs.declaration(self.root, base, "src/pkg/_version.py"))
        self.assertEqual("backend/setup.py", build_outputs.declaration(self.root, base, "backend/app/_version.py"))

    def test_an_undeclared_or_unquoted_path_or_a_later_declaration_is_not_trusted(self):
        base = self.commit({"pyproject.toml": "# src/pkg/_version.py is written by the build\n"})
        self.assertIsNone(build_outputs.declaration(self.root, base, "src/pkg/_version.py"))
        self.assertIsNone(build_outputs.declaration(self.root, base, "pkg/_version.py"))
        for name in ("/src/pkg/_version.py", "../src/pkg/_version.py", "."):
            self.assertIsNone(build_outputs.declaration(self.root, base, name))
        self.commit({"pyproject.toml": 'version-file = "src/pkg/_version.py"\n'})
        self.assertIsNone(build_outputs.declaration(self.root, base, "src/pkg/_version.py"))

    def test_a_missing_or_malformed_base_declares_nothing(self):
        self.commit({"pyproject.toml": 'version-file = "_version.py"\n'})
        for base in (None, "", "HEAD", "0" * 40):
            with self.subTest(base=base):
                self.assertIsNone(build_outputs.declaration(self.root, base, "_version.py"))

    def test_admission_needs_both_the_declaration_and_data_only_bytes(self):
        base = self.commit({"pyproject.toml": 'version-file = "_version.py"\n'})
        self.assertEqual("pyproject.toml", build_outputs.admitted(self.root, base, "_version.py", HATCH_VCS))
        self.assertIsNone(build_outputs.admitted(self.root, base, "_version.py", b"import os\n"))
        self.assertIsNone(build_outputs.admitted(self.root, base, "other.py", HATCH_VCS))


if __name__ == "__main__":
    unittest.main()
