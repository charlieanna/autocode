"""Prepare an offline Rust task at the real plan gate for the Extension Host."""

from __future__ import annotations

import dataclasses
import hashlib
import json
import os
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scenarios"))
from harness import catalog, driver  # noqa: E402,I001


OPENCODE_FLAGS = (
    "--engine",
    "opencode",
    "--task-planner-model",
    "openai/gpt-6-astra",
    "--builder-model",
    "openai/gpt-5.6-terra",
    "--tester-model",
    "zai-coding-plan/glm-5.3",
    "--completion-model",
    "zai-coding-plan/glm-5.3",
    "--planner-model",
    "zai-coding-plan/glm-5.3",
    "--plan-reviewer-model",
    "openai/gpt-6-astra",
)


def provider_path(root: Path, cargo_bin: Path, inherited: str) -> str:
    """The env-shebang provider must use the same Python as its owning fixture."""
    return os.pathsep.join((str(root / "bin"), str(Path(sys.executable).parent), str(cargo_bin), inherited))


def cargo_explicit_command(program: str, toolchain: str) -> str:
    return shlex.join([program, "+" + toolchain, "--version"])


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        raise SystemExit("usage: rustup_vscode_fixture.py ROOT")
    root = Path(argv[0]).resolve()
    root.mkdir(parents=True)
    cargo_path = shutil.which("cargo")
    if cargo_path is None:
        raise RuntimeError("The Extension Host fixture requires the installed rustup Cargo proxy")
    cargo_bin = Path(cargo_path).absolute().parent
    absolute_cargo = os.environ.get("AUTOCODE_FIXTURE_ABSOLUTE_CARGO") == "1"
    check = shlex.join([cargo_path, "--version"]) if absolute_cargo else "cargo test --offline"
    project = root / "project"
    (project / "src").mkdir(parents=True)
    (project / "Cargo.toml").write_text('[package]\nname = "fixture"\nversion = "0.1.0"\nedition = "2021"\n')
    (project / "Cargo.lock").write_text(
        "# This file is automatically @generated by Cargo.\n"
        "# It is not intended for manual editing.\n"
        'version = 4\n\n[[package]]\nname = "fixture"\nversion = "0.1.0"\n'
    )
    (project / ".gitignore").write_text("/target/\n")
    (project / "src/lib.rs").write_text(
        "pub fn sum(a:i32,b:i32)->i32 { a+b }\n"
        "#[cfg(test)] mod tests { #[test] fn addition() { assert_eq!(super::sum(2,3),5); } }\n"
    )
    subprocess.run(["git", "init", "-q", str(project)], check=True)
    subprocess.run(["git", "-C", str(project), "add", "."], check=True)
    subprocess.run(
        [
            "git",
            "-C",
            str(project),
            "-c",
            "user.name=Fixture",
            "-c",
            "user.email=fixture@example.test",
            "commit",
            "-qm",
            "base",
        ],
        check=True,
    )
    reference = root / "reference"
    shutil.copytree(project, reference, ignore=shutil.ignore_patterns(".git"))
    (reference / "README.md").write_text("A simple offline Rust fixture.\n")
    scenario = dataclasses.replace(
        catalog.load("greenfield-greeting-cli"),
        title="Rustup offline containment",
        brief=f"Document this existing Rust crate and run {check}.",
        fake_check=check,
    )
    flags, env = driver.fake_setup(scenario, root, reference)
    # The fixture owns its provider and app profiles; it does not replace the
    # operator's HOME or CODEX_HOME environment.
    env.pop("CODEX_HOME", None)
    provider = (REPO / "tools/fake_opencode.py").read_text()
    marker = 'emit("step_start", {"id": "prt_start", "type": "step-start"})'
    if provider.count(marker) != 1:
        raise AssertionError("Offline OpenCode fixture has an unexpected stage entry")
    # The checked fake uses the actual core-provided containment shell. This
    # observation does not impersonate or contact a model.
    injected = """
if agent == "autocode_builder" and os.environ.get("AUTOCODE_FIXTURE_RUSTUP_RECORD"):
    import importlib.util, traceback
    diagnostic = Path(os.environ["AUTOCODE_FIXTURE_RUSTUP_DIAGNOSTIC"])
    details = {"interpreter": sys.executable, "psutil_available": importlib.util.find_spec("psutil") is not None,
               "phase": "loading process inspection"}
    def note(): diagnostic.write_text(json.dumps(details))
    note()
    try:
        import psutil
        process = psutil.Process()
        record = (json.dumps({"pid": process.pid, "started": process.create_time()}) + "\\n").encode()
        owner = os.open(os.environ["AUTOCODE_FIXTURE_RUSTUP_OWNERS"], os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
        try: os.write(owner, record)
        finally: os.close(owner)
        import select
        fd = os.open(os.environ["AUTOCODE_FIXTURE_RUSTUP_RELEASE"], os.O_RDWR | os.O_NONBLOCK)
        try:
            details["phase"] = "executing contained Cargo"; note()
            shell = config.get("shell") or os.environ["SHELL"]
            explicit_command = os.environ["AUTOCODE_FIXTURE_RUSTUP_COMMAND"]
            explicit = subprocess.run([shell, "-c", explicit_command], capture_output=True, text=True, timeout=120)
            result = subprocess.run([shell, "-c", os.environ["AUTOCODE_FIXTURE_CARGO_CHECK"]], capture_output=True, text=True, timeout=120)
            Path(os.environ["AUTOCODE_FIXTURE_RUSTUP_RECORD"]).write_text(json.dumps({"exit":result.returncode,"stdout":result.stdout,"stderr":result.stderr,"shell":shell,"explicit_command":explicit_command,"explicit_exit":explicit.returncode,"explicit_stdout":explicit.stdout,"explicit_stderr":explicit.stderr}))
            details["phase"] = "waiting for fixture release"; note()
            if not select.select([fd], [], [], 120)[0]: raise SystemExit(124)
            os.read(fd, 1)
        finally:
            os.close(fd)
    except BaseException:
        details["error"] = traceback.format_exc(); note()
        raise
"""
    executable = root / "bin/opencode"
    executable.write_text(provider.replace(marker, marker + injected))
    executable.chmod(0o755)
    rustup = os.environ.get("RUSTUP_HOME") or str(Path.home() / ".rustup")
    installed = sorted(entry.name for entry in (Path(rustup) / "toolchains").iterdir() if entry.is_dir())
    if not installed:
        raise RuntimeError("The Extension Host fixture requires an already installed Rust toolchain")
    explicit = next((name for name in installed if name.startswith("stable-")), installed[0])
    rustup_proxy = cargo_bin / "rustup"
    if not rustup_proxy.is_file() or not os.path.samefile(cargo_path, rustup_proxy):
        raise RuntimeError("The Extension Host fixture requires Cargo to be the actual rustup proxy")
    search_path = provider_path(root, cargo_bin, os.environ.get("PATH", ""))
    env.update(
        PATH=search_path,
        RUSTUP_HOME=rustup,
        AUTOCODE_FIXTURE_QUALIFIED_OPENCODE="1",
        AUTOCODE_FIXTURE_RUSTUP_RECORD=os.environ["AUTOCODE_FIXTURE_RUSTUP_RECORD"],
        AUTOCODE_FIXTURE_RUSTUP_RELEASE=os.environ["AUTOCODE_FIXTURE_RUSTUP_RELEASE"],
        AUTOCODE_FIXTURE_RUSTUP_OWNERS=os.environ["AUTOCODE_FIXTURE_RUSTUP_OWNERS"],
        AUTOCODE_FIXTURE_RUSTUP_DIAGNOSTIC=os.environ["AUTOCODE_FIXTURE_RUSTUP_DIAGNOSTIC"],
        AUTOCODE_FIXTURE_RUSTUP_EXPLICIT=explicit,
        AUTOCODE_FIXTURE_CARGO_CHECK=check,
        AUTOCODE_FIXTURE_CARGO_PROGRAM=cargo_path if absolute_cargo else "cargo",
        AUTOCODE_FIXTURE_RUSTUP_COMMAND=cargo_explicit_command(cargo_path if absolute_cargo else "cargo", explicit),
    )
    run_driver = driver.Driver(
        project,
        root,
        [*flags, *OPENCODE_FLAGS, "--max-seconds", "600"],
        env,
        autocode=[sys.executable, str(REPO / "tools/autocode.py")],
        max_steps=50,
        timeout_seconds=300,
    )
    run_driver.call("start", task=scenario.brief)
    runs = list((project / ".autocode/runs").glob("*/state.json"))
    if len(runs) != 1:
        raise AssertionError("Offline fixture did not create exactly one run")
    run_driver.run_dir = runs[0].parent
    view = run_driver.until_stopped(say_at="needs:approve_plan")
    if (view.get("needs") or {}).get("kind") != "approve_plan":
        raise AssertionError(f"Offline Rust task did not reach its plan gate: {view.get('status')}")
    if absolute_cargo:
        # Pre-plan roles have no selected command and use manifest discovery.
        # The approved action and all later stages receive the off-PATH setup.
        run_driver.env["PATH"] = os.pathsep.join(
            entry for entry in search_path.split(os.pathsep) if entry and Path(entry).resolve() != cargo_bin.resolve()
        )
        if shutil.which("cargo", path=run_driver.env["PATH"]):
            raise RuntimeError("The absolute-Cargo fixture requires Cargo to be absent from PATH")
    if any(run_driver.env.get(name) != os.environ.get(name) for name in ("HOME", "CODEX_HOME")):
        raise AssertionError("The offline fixture changed the operator's HOME or CODEX_HOME")
    plan = view["displayed_plan"]
    criteria = plan["acceptance_criteria"]
    allowed = {"Cargo.toml", "Cargo.lock", ".gitignore", "src/lib.rs", "README.md"}
    paths = {path for milestone in plan["milestones"] for path in milestone.get("affected_paths", [])}
    if (
        len(criteria) != 1
        or criteria[0].get("verification_method") != check
        or not paths <= allowed
        or plan.get("permission_boundaries") != ["Read and edit only this scenario workspace"]
        or hashlib.sha256(plan["review_markdown"].replace(shlex.quote(cargo_path), "cargo").encode()).hexdigest()
        != (
            "7f2deddb564dc2e39e23bf380636808c7cb1081c18477f1d0455d1957c21829a"
            if absolute_cargo
            else "77170cecfe2dc70dd77771f010bab94aec2087c359f2c2cc4dd5f328f3a464ab"
        )
    ):
        raise AssertionError("The exact generated plan exceeds the reviewed offline Rust task")
    review = root / "agent-plan-review.json"
    review.write_text(
        json.dumps(
            {
                "token": plan["token"],
                "review_markdown": plan["review_markdown"],
                "review": "Operating agent review under the owner's delegation; offline fixture only.",
            }
        )
    )
    names = (
        "PATH",
        "AUTOCODE_HOME",
        "XDG_CONFIG_HOME",
        "SCENARIO_FAKE_CONFIG",
        "PYTHONDONTWRITEBYTECODE",
        "RUSTUP_HOME",
        "AUTOCODE_FIXTURE_QUALIFIED_OPENCODE",
        "AUTOCODE_FIXTURE_RUSTUP_RECORD",
        "AUTOCODE_FIXTURE_RUSTUP_RELEASE",
        "AUTOCODE_FIXTURE_RUSTUP_OWNERS",
        "AUTOCODE_FIXTURE_RUSTUP_DIAGNOSTIC",
        "AUTOCODE_FIXTURE_RUSTUP_EXPLICIT",
        "AUTOCODE_FIXTURE_CARGO_CHECK",
        "AUTOCODE_FIXTURE_CARGO_PROGRAM",
        "AUTOCODE_FIXTURE_RUSTUP_COMMAND",
        "AUTOCODE_REPLAY_EMITTER_COMMAND",
        "AUTOCODE_REPLAY_FIXTURE_ROOT",
    )
    print(
        json.dumps(
            {
                "workspace": str(project),
                "runDir": str(run_driver.run_dir),
                "env": {name: run_driver.env[name] for name in names if name in run_driver.env},
                "planToken": plan["token"],
                "planReview": str(review),
            }
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
