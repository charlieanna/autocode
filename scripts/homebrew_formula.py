#!/usr/bin/env python3
"""Write the Homebrew formula for a published AutoCode release.

    python3 scripts/homebrew_formula.py 0.8.0 > ../homebrew-tap/Formula/autocode.rb

It reads PyPI's JSON for the ``autocode-supervisor`` sdist of that version and for the newest
sdist of each runtime dependency that pyproject's range allows, so the formula pins exact
files by their sha256. Run it after the release is on PyPI (docs/releasing.md#homebrew).
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
import urllib.request
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROJECT = "autocode-supervisor"
PYTHON = "python@3.13"

Fetch = Callable[[str], dict]


def pypi(path: str) -> dict:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{path}/json", timeout=30) as response:
        return json.load(response)


def sdist(release: dict, name: str) -> dict:
    """The release's source distribution: Homebrew builds from source, never from a wheel."""
    for row in release.get("urls", []):
        if row.get("packagetype") == "sdist":
            return {"url": row["url"], "sha256": row["digests"]["sha256"]}
    raise SystemExit(f"{name} {release.get('info', {}).get('version')} has no sdist on PyPI")


def version_key(text: str) -> tuple[int, ...]:
    return tuple(int(part) for part in text.split("."))


def allowed(requirement: str) -> tuple[str, Callable[[str], bool]]:
    """A dependency such as ``psutil>=7.1,<8``: its name and whether a plain release fits."""
    name = requirement.split(">")[0].split("<")[0].split("=")[0].split(";")[0].strip()
    bounds = [part.strip() for part in requirement[len(name) :].split(",") if part.strip()]

    def fits(version: str) -> bool:
        if not all(part.isdigit() for part in version.split(".")):
            return False  # pre-releases and post-releases are never pinned
        key = version_key(version)
        for bound in bounds:
            for op in (">=", "<=", "==", ">", "<"):
                if bound.startswith(op):
                    limit = version_key(bound[len(op) :].strip())
                    width = max(len(key), len(limit))
                    a, b = key + (0,) * (width - len(key)), limit + (0,) * (width - len(limit))
                    if not {">=": a >= b, "<=": a <= b, "==": a == b, ">": a > b, "<": a < b}[op]:
                        return False
                    break
            else:
                raise SystemExit(f"cannot read the bound {bound!r} in {requirement!r}")
        return True

    return name, fits


def resource(requirement: str, fetch: Fetch) -> dict:
    name, fits = allowed(requirement)
    releases = fetch(name).get("releases", {})
    versions = sorted((v for v, files in releases.items() if files and fits(v)), key=version_key)
    if not versions:
        raise SystemExit(f"no release of {name} on PyPI fits {requirement!r}")
    return {"name": name, **sdist(fetch(f"{name}/{versions[-1]}"), name)}


def formula(version: str, pyproject: dict, fetch: Fetch = pypi) -> str:
    project = pyproject["project"]
    if project["version"] != version:
        raise SystemExit(f"pyproject.toml names {project['version']}, not {version}")
    source = sdist(fetch(f"{PROJECT}/{version}"), PROJECT)
    resources = [resource(requirement, fetch) for requirement in project.get("dependencies", [])]
    blocks = "".join(
        f'\n  resource "{row["name"]}" do\n    url "{row["url"]}"\n    sha256 "{row["sha256"]}"\n  end\n'
        for row in resources
    )
    description = "Runs your coding agent and won't say done without evidence"
    return f"""# Generated by scripts/homebrew_formula.py from the PyPI release; regenerate, do not edit.
class Autocode < Formula
  include Language::Python::Virtualenv

  desc "{description}"
  homepage "https://github.com/charlieanna/autocode"
  url "{source["url"]}"
  sha256 "{source["sha256"]}"
  license "Apache-2.0"

  depends_on "{PYTHON}"
{blocks}
  def install
    venv = virtualenv_create(libexec, "python3.13")
    venv.pip_install resources
    venv.pip_install buildpath
    # Only `autocode` is public; the package's other scripts are internal aliases.
    bin.install_symlink libexec/"bin/autocode"
  end

  test do
    assert_match "autocode #{{version}} ", shell_output("#{{bin}}/autocode --version")
  end
end
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("version", help="the released version, as in pyproject.toml (0.8.0)")
    args = parser.parse_args(argv)
    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text())
    sys.stdout.write(formula(args.version, pyproject))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
